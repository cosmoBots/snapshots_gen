# frozen_string_literal: true

# Compares the rendered histories of an old instance and a migrated one
# (two outputs of history_text.rb), item by item through the CSID.
#
#   ruby compare_history.rb SOURCE.jsonl TARGET.jsonl [REPORT.json] [--show CSID]
#
# REPORT.json is the conversion report: source journals it lists as dropped
# are expected to be missing in the target.
# Exact equality is not expected for everything the conversion renames on
# purpose (rq* statuses and fields, chapter numbers, reference ids); those
# differences are printed for review. Authors, dates, notes and the number of
# journals must match, and no line may say "Translation missing" or show a
# journal as edited.

require 'json'
require 'set'

def load(path)
  File.foreach(path).map { |line| JSON.parse(line) }.to_h { |row| [row['csid'], row] }
end

source = load(ARGV[0])
target = load(ARGV[1])
report = ARGV[2] && !ARGV[2].start_with?('--') ? JSON.parse(File.read(ARGV[2])) : { 'entries' => [] }
dropped = report['entries'].select { |entry| entry['code'] == 'history_journal_dropped' }
                           .map { |entry| entry['subject'].to_s[/journal #(\d+)/, 1].to_i }.to_set
show = ARGV.include?('--show') ? ARGV[ARGV.index('--show') + 1] : nil
failures = []
reviews = []
product_gaps = Set.new
normalize_notes = ->(text) { text.to_s.gsub(/!?#\d+/, '#N') }

source.each do |csid, old|
  new = target[csid]
  if new.nil?
    reviews << "#{csid}: not in the target (absorbed or renumbered)"
    next
  end
  %w[author created updated closed watchers time].each do |key|
    failures << "#{csid}: #{key} #{old[key].inspect} -> #{new[key].inspect}" unless old[key] == new[key]
  end
  old_journals = old['journals'].reject { |journal| dropped.include?(journal['id']) }
  new_journals = new['journals']
  failures << "#{csid}: #{old_journals.length} journals -> #{new_journals.length}" if old_journals.length != new_journals.length
  old_journals.zip(new_journals).each_with_index do |(before, after), index|
    next unless after

    %w[at by private].each do |key|
      failures << "#{csid} journal #{index + 1}: #{key} #{before[key].inspect} -> #{after[key].inspect}" unless before[key] == after[key]
    end
    failures << "#{csid} journal #{index + 1}: shows as edited" if after['edited']
    unless normalize_notes.call(before['notes']) == normalize_notes.call(after['notes'])
      failures << "#{csid} journal #{index + 1}: notes differ"
    end
    after['details'].each do |line|
      next unless line.match?(/translation missing/i)

      # cosmoSys lacks these labels for any change of its native fields.
      if line.match?(/field_cs_(ext_code|wload)/)
        product_gaps << line[/field_cs_\w+/]
      else
        failures << "#{csid} journal #{index + 1}: #{line}"
      end
    end
    reviews << "#{csid} journal #{index + 1}: #{before['details'].inspect} -> #{after['details'].inspect}" if before['details'] != after['details']
  end
  next unless show == csid

  puts "#{csid} source: #{JSON.pretty_generate(old)}"
  puts "#{csid} target: #{JSON.pretty_generate(new)}"
end
(target.keys - source.keys).each { |csid| reviews << "#{csid}: only in the target (generated by the conversion)" }
puts "Items: #{source.length} in the source, #{target.length} in the target"
puts "Differences to review (#{reviews.length}):"
reviews.each { |line| puts "  #{line}" }
if product_gaps.any?
  puts "Labels cosmoSys lacks for its own native fields (#{product_gaps.to_a.sort.join(', ')}): " \
       'their changes read "Translation missing" until cosmoSys adds them.'
end
puts "Failures (#{failures.length}):"
failures.each { |line| puts "  #{line}" }
exit(failures.empty? ? 0 : 1)
